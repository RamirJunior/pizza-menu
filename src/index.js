function Footer() {
  const hour = new Date().getHours();
  const openHour = 12;
  const closeHour = 22;
  const isOpen = hour >= openHour && hour <= closeHour;
  console.log(isOpen);

  // if (hour >= openHour && hour <= closeHour) alert("Estamos funcionando!");
  // else alert("Desculpe, estamos fechados!");

  if (!isOpen) return <p>FECHADO</p>;

  return (
    <footer className="footer">
      {isOpen ? (
        <Order openHour={openHour} closeHour={closeHour} />
      ) : (
        <p>
          Ficaremos felizes em atender você entre {openHour}:00 e {closeHour}
          :00.
        </p>
      )}
    </footer>
  );
}

function Order({ openHour, closeHour }) {
  return (
    <div className="order">
      <p>
        Estamos funcionando entre {openHour}:00 e {closeHour}:00. Visite-nos ou
        peça online.
      </p>
      <button className="btn">Pedir agora</button>
    </div>
  );
}

